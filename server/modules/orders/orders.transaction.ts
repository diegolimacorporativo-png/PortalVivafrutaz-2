import { eq, sql } from "drizzle-orm";
import { db } from "../../database/db";
import {
  orders,
  deliveries,
  workflowEvents,
  type WorkflowEventPayload,
} from "@shared/schema";
import { legacyStatusFor, OrderStatus } from "./orders.workflow";
import { BadRequestError, ConflictError } from "../../shared/errors/AppError";
import { areOrderDeliveriesDelivered } from "../logistics/delivery-completion.service";

// ─── Compatibility helper ─────────────────────────────────────────────────────
// `tx.execute(sql\`…\`)` returns either a plain row array (older drizzle) or a
// `QueryResult`-shaped `{ rows, command, fields, … }` (current drizzle/node-pg).
// `rowsOf` normalizes both shapes so destructuring/iteration is safe regardless
// of the underlying driver version.
function rowsOf<T = any>(result: unknown): T[] {
  if (Array.isArray(result)) return result as T[];
  const rows = (result as { rows?: T[] } | null)?.rows;
  return Array.isArray(rows) ? rows : [];
}

// ─── Result types ─────────────────────────────────────────────────────────────

export interface CriticalTransitionResult {
  /** The updated order row (both workflowStatus and status are already synced). */
  updatedOrder: typeof orders.$inferSelect;
  /** Pre-nota number generated by this transition, when applicable. */
  preNotaNumber: string | null;
  /** Whether approval created the initial delivery record. */
  deliveryCreated: boolean;
  /** Whether the logistics delivery row was updated (SHIPPED only). */
  deliveryUpdated: boolean;
}

// ─── Inputs ───────────────────────────────────────────────────────────────────

export interface TransactionInput {
  orderId: number;
  to: OrderStatus;
  /**
   * The workflowStatus the caller observed BEFORE entering the transaction.
   * Used as an optimistic-lock token: if the DB row shows a different value,
   * a concurrent request already committed — we reject with 409.
   */
  expectedWorkflowStatus: string;
  /** Current value of orders.status (legacy column) read pre-transaction. */
  currentLegacyStatus: string;
  /** Order row snapshot read BEFORE the transaction begins. */
  orderSnapshot: any;
  /** Company snapshot used to initialize delivery address metadata. */
  companySnapshot: any;
  /** User performing the action (for the outbox). */
  actor: { id: number; email: string; role: string; name?: string };
  /** The workflowStatus before the transition (for outbox payload). */
  from: string;
}

// ─── Main entry-point ─────────────────────────────────────────────────────────

/**
 * Execute all critical DB writes for a workflow transition in a single
 * PostgreSQL transaction with full concurrency safety.
 *
 * ─── Concurrency model ───────────────────────────────────────────────────────
 *
 * 1. pg_try_advisory_xact_lock(orderId)  — distributed application lock
 *    Acquired as the very first statement. Returns `true` if the lock was
 *    granted, `false` if another transaction already holds it for this order.
 *    On false → throw ConflictError(409) → ROLLBACK (lock never held).
 *    This is a transaction-level lock: PostgreSQL releases it automatically
 *    at COMMIT or ROLLBACK — no cleanup code needed.
 *    Works across every Node.js process and database connection, making
 *    horizontal scaling (multiple replicas) safe with no extra infrastructure.
 *
 * 2. Optimistic-lock check (state verify after lock)
 *    After acquiring the application lock, re-read `workflow_status` from the
 *    order row. If it no longer matches `expectedWorkflowStatus` (the value
 *    the caller observed before opening this transaction), a concurrent
 *    request already committed — throw ConflictError so the caller retries
 *    with fresh state.
 *
 * 3. The initial delivery is ensured idempotently in this transaction on
 *    approval, so a successful release cannot be committed without it.
 *
 * 4. Transactional outbox (event reliability)
 *    The last write inside the transaction is an INSERT into `workflow_events`.
 *    Because this INSERT is inside the same transaction as the order update,
 *    the event is guaranteed to exist if and only if the transition committed.
 *    A background worker (orders.outbox.worker.ts) polls the table and
 *    executes non-critical side effects (push notification, audit log) with
 *    retry semantics and `FOR UPDATE SKIP LOCKED` so multiple workers never
 *    process the same event.
 *
 * ─── Rollback guarantee ──────────────────────────────────────────────────────
 *    Drizzle wraps the callback in BEGIN … COMMIT / ROLLBACK. Any unhandled
 *    throw inside `db.transaction(async tx => …)` triggers automatic ROLLBACK
 *    before the error propagates to the caller. No partial state ever persists.
 */
export async function executeWorkflowTransaction(
  input: TransactionInput,
): Promise<CriticalTransitionResult> {
  const {
    orderId,
    to,
    from,
    expectedWorkflowStatus,
    currentLegacyStatus,
    orderSnapshot,
    companySnapshot,
    actor,
  } = input;
  const newLegacyStatus = legacyStatusFor(to, currentLegacyStatus);

  return db.transaction(async (tx) => {

    // ── Step 1: Distributed application lock ────────────────────────────────
    //
    // pg_try_advisory_xact_lock(key) grants an exclusive lock for this
    // transaction's lifetime. Unlike SELECT … FOR UPDATE it does not block —
    // it returns false immediately if another transaction already holds it.
    // This makes the behaviour predictable (fast fail, no queue pile-up).
    const lockResult = rowsOf<{ acquired: boolean }>(
      await tx.execute(
        sql`SELECT pg_try_advisory_xact_lock(${orderId}::bigint) AS acquired`,
      ),
    )[0];

    if (!lockResult) {
      throw new BadRequestError("Falha ao obter lock do pedido");
    }
    if (!lockResult.acquired) {
      throw new ConflictError(
        `Pedido #${orderId} já está sendo processado em outro servidor. ` +
        `Aguarde um momento e tente novamente.`,
        { orderId },
      );
    }

    // ── Step 2: Optimistic-lock check ───────────────────────────────────────
    //
    // Re-read the current workflow_status now that we hold the advisory lock.
    // If it changed, a concurrent request already committed a transition.
    const currentRow = rowsOf<{
      workflow_status: string;
      company_id: number;
    }>(
      await tx.execute(
        sql`SELECT workflow_status, company_id
            FROM orders
            WHERE id = ${orderId}
            FOR UPDATE`,
      ),
    )[0];

    if (!currentRow) {
      throw new ConflictError(
        "Pedido não encontrado. Pode ter sido excluído simultaneamente.",
      );
    }

    if (currentRow.workflow_status !== expectedWorkflowStatus) {
      throw new ConflictError(
        `O pedido foi modificado simultaneamente. ` +
        `Estado esperado: ${expectedWorkflowStatus}, ` +
        `estado atual: ${currentRow.workflow_status}. ` +
        `Recarregue e tente novamente.`,
        {
          expectedWorkflowStatus,
          currentWorkflowStatus: currentRow.workflow_status,
        },
      );
    }
    if (currentRow.company_id !== orderSnapshot.companyId) {
      throw new ConflictError(
        "A empresa do pedido foi alterada durante a operação. Recarregue e tente novamente.",
      );
    }

    if (to === OrderStatus.APPROVED) {
      const companyRows = rowsOf<{ active: boolean; is_locked: boolean; company_name: string }>(
        await tx.execute(
          sql`SELECT active, is_locked, company_name
              FROM companies
              WHERE id = ${currentRow.company_id}
              FOR SHARE`,
        ),
      );
      const currentCompany = companyRows[0];
      if (!currentCompany || !currentCompany.active || currentCompany.is_locked) {
        throw new BadRequestError(
          `Empresa ${currentCompany?.company_name ? `"${currentCompany.company_name}" ` : ""}está inativa ou bloqueada e não pode ter pedidos aprovados.`,
        );
      }
    }

    // Finalization is allowed only after every linked delivery is already
    // terminal. Never use the order transition to manufacture delivered rows:
    // the delivery/checklist completion flow owns delivery timestamps and events.
    if (to === OrderStatus.DELIVERED) {
      const linkedDeliveries = rowsOf<{
        id: number;
        company_id: number | null;
        status: string;
        route_id: number | null;
        route_company_id: number | null;
      }>(
        await tx.execute(
          sql`SELECT d.id,
                     d.company_id,
                     d.status,
                     d.route_id,
                     r.empresa_id AS route_company_id
              FROM deliveries d
              LEFT JOIN logistics_routes r ON r.id = d.route_id
              WHERE d.order_id = ${orderId}
              ORDER BY d.id
              FOR UPDATE OF d`,
        ),
      );

      if (linkedDeliveries.length === 0) {
        throw new BadRequestError(
          "O pedido não pode ser entregue sem entregas vinculadas.",
        );
      }

      for (const delivery of linkedDeliveries) {
        if (
          (delivery.company_id != null &&
            delivery.company_id !== orderSnapshot.companyId) ||
          (delivery.route_id != null &&
            delivery.route_company_id !== orderSnapshot.companyId)
        ) {
          throw new BadRequestError(
            "O vínculo entre pedido, empresa, entrega e rota é inconsistente.",
          );
        }
      }

      if (!areOrderDeliveriesDelivered(linkedDeliveries)) {
        throw new BadRequestError(
          "O pedido só pode ser marcado como entregue quando todas as entregas vinculadas estiverem efetivamente entregues.",
        );
      }
    }

    // ── Step 3: Commit the state transition ─────────────────────────────────
    const [updatedOrder] = await tx
      .update(orders)
      .set({ workflowStatus: to, status: newLegacyStatus })
      .where(eq(orders.id, orderId))
      .returning();

    if (!updatedOrder) {
      // Defensive: the optimistic-lock check above proved the row exists and
      // matches expectedWorkflowStatus, so an empty .returning() here would
      // signal a concurrent DELETE between the two reads. Surface as 409.
      throw new ConflictError(
        `Pedido #${orderId} não pôde ser atualizado (linha desapareceu durante a transação).`,
        { orderId },
      );
    }

    let preNotaNumber: string | null = null;
    let deliveryCreated = false;
    let deliveryUpdated = false;

    // ── Step 4a: APPROVED — create an initial delivery atomically ──────────
    if (to === OrderStatus.APPROVED) {
      // The workflow lock above also serializes the auto-delivery path.
      const existingDelivery = await tx
        .select({ id: deliveries.id })
        .from(deliveries)
        .where(eq(deliveries.orderId, orderId))
        .limit(1);

      if (existingDelivery.length === 0) {
        const deliveryDate = orderSnapshot.deliveryDate instanceof Date
          ? orderSnapshot.deliveryDate.toISOString().slice(0, 10)
          : new Date(orderSnapshot.deliveryDate).toISOString().slice(0, 10);
        await tx.insert(deliveries).values({
          orderId,
          companyId: orderSnapshot.companyId,
          status: "pendente",
          scheduledDate: deliveryDate,
          addressStreet: companySnapshot?.addressStreet || null,
          addressNumber: companySnapshot?.addressNumber || null,
          addressCity: companySnapshot?.addressCity || null,
          addressState: companySnapshot?.addressState || null,
          addressZip: companySnapshot?.addressZip?.replace(/\D/g, "") || null,
          latitude: companySnapshot?.latitude || null,
          longitude: companySnapshot?.longitude || null,
          notes: `Auto-entrada: pedido ${orderSnapshot.orderCode || `#${orderId}`}`,
        });
        deliveryCreated = true;
      }
    }

    // ── Step 4b: SHIPPED — conditional delivery row update ──────────────────
    if (to === OrderStatus.SHIPPED) {
      // Only update if currently 'pendente' — idempotent and status-safe.
      const updated = rowsOf<{ id: number }>(
        await tx.execute(
          sql`UPDATE deliveries
              SET    status     = 'em_rota',
                     updated_at = NOW()
              WHERE  order_id   = ${orderId}
                AND  status     = 'pendente'
              RETURNING id`,
        ),
      );

      deliveryUpdated = updated.length > 0;
    }

    // ── Step 5: Write outbox event (transactional reliability) ──────────────
    //
    // This INSERT is part of the same transaction. If the transaction rolls
    // back for any reason the event disappears too — there is no "phantom
    // event for a failed transition" problem. The background worker
    // (orders.outbox.worker.ts) reads from this table to execute push
    // notifications and audit logs with retry semantics.
    const outboxPayload: WorkflowEventPayload = {
      orderId,
      orderCode:  orderSnapshot.orderCode || null,
      companyId:  orderSnapshot.companyId,
      from,
      to,
      actor,
      result: {
        preNotaNumber,
        deliveryCreated,
        deliveryUpdated,
      },
    };

    // MT-3B M3 — STRUCTURAL RISK: workflow_events has no direct tenantId/empresaId column.
    // Tenant identity is embedded in outboxPayload.companyId. The outbox worker reads
    // this field to establish tenant context before processing each event.
    // Future: add a tenant column for DB-level isolation (not MT-3B scope — no migration here).
    await tx.insert(workflowEvents).values({
      orderId,
      eventType: "TRANSITION",
      payload:   outboxPayload as any,
    });

    return {
      updatedOrder,
      preNotaNumber,
      deliveryCreated,
      deliveryUpdated,
    };
  });
}
